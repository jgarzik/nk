#!/usr/bin/env python3
"""Write lib/rtl/doserror_table.rs: the pinned kernel's mapping from
status codes to Windows error codes, which RtlNtStatusToDosErrorNoTeb
searches (doc/design/rtl.md, Status codes).

Usage: doserror.py <ntoskrnl.exe> <output.rs>

The kernel (10.0.19041.2006, the corpus fixture) keeps the mapping as two
tables its routine reads by RVA: 0x135 runs of status codes (base u32,
count u8, entry width in u16 units u8, index u16), sorted, and the u16
entries they index. Those RVAs belong to this build only, and the script
checks the routine still reads them before it trusts them.
"""

import struct
import sys

RUNS_RVA = 0x197F0
RUNS = 0x135
ENTRIES_RVA = 0x179D0
ROUTINE_RVA = 0x332CA0


def sections(image):
    pe = struct.unpack_from("<I", image, 0x3C)[0]
    count = struct.unpack_from("<H", image, pe + 6)[0]
    optional = struct.unpack_from("<H", image, pe + 20)[0]
    return [struct.unpack_from("<8sIIII", image, pe + 24 + optional + i * 40)
            for i in range(count)]


def reader(image):
    table = sections(image)

    def read(rva, length):
        for _, vsize, vaddr, rsize, raw in table:
            if vaddr <= rva < vaddr + max(vsize, rsize):
                return image[raw + rva - vaddr:raw + rva - vaddr + length]
        raise SystemExit(f"RVA {rva:#x} is in no section")
    return read


def main():
    image = open(sys.argv[1], "rb").read()
    read = reader(image)
    # The routine's search loads the run table by RVA from the image base
    # (mov eax, [rbx+rcx*8+RUNS_RVA]) and its bound (mov r9d, RUNS-1).
    code = read(ROUTINE_RVA, 0xC0)
    if (struct.pack("<I", RUNS_RVA) not in code
            or struct.pack("<I", ENTRIES_RVA) not in code
            or struct.pack("<I", RUNS - 1) not in code):
        raise SystemExit("this kernel does not read the tables where 19041.2006 does")
    runs = [struct.unpack("<IBBH", read(RUNS_RVA + i * 8, 8)) for i in range(RUNS)]
    end = max(index + count * width for _, count, width, index in runs)
    entries = struct.unpack(f"<{end}H", read(ENTRIES_RVA, end * 2))
    previous = 0
    for base, count, width, _ in runs:
        assert base >= previous and width in (1, 2)
        previous = base + count
    out = ["// Generated by tools/doserror.py from ntoskrnl.exe 10.0.19041.2006.",
           "// Do not edit.", "",
           "/// Runs of status codes: (first code, how many, entry width in",
           "/// 16-bit units, index of the first entry in [`ENTRIES`]).",
           "#[rustfmt::skip]",
           f"pub static RUNS: [(u32, u8, u8, u16); {len(runs)}] = ["]
    out += [f"    (0x{b:08X}, {c}, {w}, {i})," for b, c, w, i in runs]
    out += ["];", "", "/// The Windows error codes, 16 bits a unit.", "#[rustfmt::skip]",
            f"pub static ENTRIES: [u16; {end}] = ["]
    for at in range(0, end, 12):
        out.append("    " + " ".join(f"{v}," for v in entries[at:at + 12]))
    out += ["];", ""]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
