//! Link settings and build-time code generation for the kernel image.
//!
//! 1. The UEFI targets default to an EFI application whose entry point is
//!    `efi_main`. The kernel is a PE image started by nkload, not by firmware:
//!    name its real entry point and mark it a native (kernel-mode) image.
//! 2. Generates the 471-entry NT system service metadata table from the
//!    committed `svc/services.tsv` (verified against `ntdll.dll` by
//!    `tools/svctable.py`).

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo:rustc-link-arg-bins=/entry:nk_entry");
    println!("cargo:rustc-link-arg-bins=/subsystem:native");
    // A link map beside the image (`nkkrnl.map`): `tools/unwind_coverage.py`
    // names the code without unwind entries from it. Build scripts get
    // an output directory somewhere under `build/`, which sits beside
    // the image.
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let image_dir = out
        .ancestors()
        .find(|dir| dir.file_name().is_some_and(|name| name == "build"))
        .and_then(|build| build.parent())
        .expect("OUT_DIR is under build/");
    println!(
        "cargo:rustc-link-arg-bins=/map:{}",
        image_dir.join("nkkrnl.map").display()
    );

    generate_service_table(&out);
}

fn generate_service_table(out_dir: &std::path::Path) {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"),
    );
    let tsv_path = manifest_dir.join("svc").join("services.tsv");
    println!("cargo:rerun-if-changed={}", tsv_path.display());

    let contents = std::fs::read_to_string(&tsv_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", tsv_path.display()));
    let mut rows: Vec<(u16, String, u8, bool)> = Vec::new();
    for (lineno, raw) in contents.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let parts: Vec<&str> = line.split('\t').collect();
        assert_eq!(
            parts.len(),
            4,
            "{}:{}: expected 4 columns",
            tsv_path.display(),
            lineno + 1
        );
        let num: u16 = parts[0].parse().expect("service number");
        let name = parts[1].to_owned();
        let stack_args: u8 = parts[2].parse().expect("stack_args");
        let has_stub = match parts[3] {
            "yes" => true,
            "no" => false,
            other => panic!("unexpected ntdll_stub value {other:?}"),
        };
        assert_eq!(
            num as usize,
            rows.len(),
            "service table numbers must be contiguous from 0"
        );
        rows.push((num, name, stack_args, has_stub));
    }

    let mut code = String::with_capacity(48 * 1024);
    writeln!(
        code,
        "// Generated by kernel/build.rs from kernel/svc/services.tsv. Do not edit."
    )
    .unwrap();
    writeln!(code, "pub const SERVICE_COUNT: usize = {};", rows.len()).unwrap();
    writeln!(code, "#[derive(Clone, Copy)]").unwrap();
    writeln!(code, "#[allow(dead_code)]").unwrap();
    writeln!(code, "pub struct ServiceMeta {{").unwrap();
    writeln!(code, "    pub number: u16,").unwrap();
    writeln!(code, "    pub name: &'static str,").unwrap();
    writeln!(code, "    pub stack_args: u8,").unwrap();
    writeln!(code, "    pub ntdll_stub: bool,").unwrap();
    writeln!(code, "}}").unwrap();
    writeln!(code, "#[allow(non_upper_case_globals, dead_code)]").unwrap();
    writeln!(code, "pub mod nr {{").unwrap();
    for (num, name, _, _) in &rows {
        writeln!(code, "    pub const {name}: u16 = {num};").unwrap();
    }
    writeln!(code, "}}").unwrap();
    writeln!(
        code,
        "pub static SERVICE_META: [ServiceMeta; SERVICE_COUNT] = ["
    )
    .unwrap();
    for (num, name, stack_args, has_stub) in &rows {
        writeln!(
            code,
            "    ServiceMeta {{ number: {num}, name: {name:?}, stack_args: {stack_args}, ntdll_stub: {has_stub} }},"
        )
        .unwrap();
    }
    writeln!(code, "];").unwrap();

    std::fs::write(out_dir.join("svc_table.rs"), code).expect("write svc_table.rs");
}
