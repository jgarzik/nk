//! `\Driver\PnpManager`: the Plug and Play manager's own driver. It
//! owns the device at the root of the tree (`HTREE\ROOT\0`) and the
//! physical device object of every device a driver reports for itself
//! ([`report_detected_device`], Windows' `IoReportDetectedDevice`):
//! the HAL's, `ROOT\ACPI_HAL\0000`.
//!
//! The root's children are the reported devices. A reported device is
//! served by the driver that reported it, which attaches its own
//! device; the manager's device below it answers who the device is and
//! succeeds what a bus driver succeeds for a device that is simply
//! there.

use super::node::{self, Node, State};
use super::registry::{self, REG_DWORD, REG_MULTI_SZ, REG_SZ};
use crate::io::{device, driver, irp};
use crate::mm::pool;
use alloc::format;
use alloc::vec::Vec;
