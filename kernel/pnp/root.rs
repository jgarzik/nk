use nk_pnp::ids;

/// The instance path of the root.
pub const ROOT_INSTANCE: &str = "HTREE\\ROOT\\0";

/// `FILE_DEVICE_CONTROLLER`: the type Windows gives the manager's
/// devices.
const FILE_DEVICE_CONTROLLER: u32 = 4;
/// `FILE_AUTOGENERATED_DEVICE_NAME`.
pub const FILE_AUTOGENERATED_DEVICE_NAME: u32 = 0x80;
/// `DO_BUS_ENUMERATED_DEVICE`.
const DO_BUS_ENUMERATED_DEVICE: u32 = 0x1000;

static DRIVER: AtomicPtr<DRIVER_OBJECT> = AtomicPtr::new(core::ptr::null_mut());
static ROOT: AtomicPtr<DEVICE_OBJECT> = AtomicPtr::new(core::ptr::null_mut());

/// The root device.
pub fn root() -> *mut DEVICE_OBJECT {
    ROOT.load(Ordering::Acquire)
}

/// A string for a driver: its units, zero-terminated (twice, for a
/// list), in a pool block the receiver frees. Null without memory.
pub fn pool_string(units: &[u16]) -> usize {
    let bytes = units.len() * 2;
    let block = pool::alloc(bytes, super::TAG);
    if !block.is_null() {
        // SAFETY: a fresh block of that many bytes.
        unsafe { block.copy_from_nonoverlapping(units.as_ptr().cast(), bytes) };
    }
    block as usize
}

/// Complete `request` with `status` and `information`.
///
/// # Safety
/// `request` is an IRP its caller owns.
pub unsafe fn complete(request: *mut IRP, status: NTSTATUS, information: usize) -> NTSTATUS {
    // SAFETY: per the contract.
    unsafe {
        (*request).IoStatus.Status = status;
        (*request).IoStatus.Information = information;
        irp::IofCompleteRequest(request, 0);
    }
    status
}

/// Complete `request` as it came: nobody below handles it.
///
/// # Safety
/// `request` is an IRP its caller owns.
pub unsafe fn complete_unchanged(request: *mut IRP) -> NTSTATUS {
    // SAFETY: per the contract.
    unsafe {
        let status = (*request).IoStatus.Status;
        irp::IofCompleteRequest(request, 0);
        status
    }
}

/// A `DEVICE_RELATIONS` naming `devices`, each referenced, in a pool
/// block the receiver frees. Zero without memory.
pub fn relations_of(devices: &[usize]) -> usize {
    let size = device_relations_size(devices.len().max(1));
    let block = pool::alloc_zeroed(size, super::TAG).cast::<DEVICE_RELATIONS>();
    if block.is_null() {
        return 0;
    }
    // SAFETY: a fresh block with room for the count and the pointers;
    // each device is live, and referenced for the receiver.
    unsafe {
        (&raw mut (*block).Count).write(devices.len() as u32);
        let objects = (&raw mut (*block).Objects).cast::<usize>();
        for (at, device) in devices.iter().enumerate() {
            crate::ob::object::reference(*device as *mut u8);
            objects.add(at).write(*device);
        }
    }
    block as usize
}

/// Discover pre-installed root-enumerated devices under
/// `ControlSet001\Enum\ROOT\<Device>\<Instance>` (such as `ROOT\ECHO\0000`),
/// skipping `LEGACY_*` keys, dynamically reported devices (`DeviceReported=1`),
/// and instances already present in the device tree.
fn discover_registry_devices() {
    let root_enum = "Machine\\System\\CurrentControlSet\\Enum\\ROOT";
    let root_pdo = root() as usize;
    if root_pdo == 0 {
        return;
    }
    for device_key in crate::cm::subkeys(root_enum) {
        if device_key
            .get(..7)
            .is_some_and(|p| p.eq_ignore_ascii_case("LEGACY_"))
        {
            continue;
        }
        let device_path = format!("{root_enum}\\{device_key}");
        for inst_key in crate::cm::subkeys(&device_path) {
            let instance = format!("ROOT\\{device_key}\\{inst_key}");
            if node::by_instance(&instance).is_some() {
                continue;
            }
            let key = registry::enum_key(&instance);
            if registry::dword(&key, "DeviceReported") == Some(1) {
                continue;
            }
            // Only enumerate entries explicitly configured as root PnP devices
            // (with HardwareID and/or Service, and not marked DeviceReported).
            let has_hw = crate::cm::read(&key, "HardwareID").is_ok();
            let has_svc = registry::string(&key, "Service").is_some();
            if !has_hw && !has_svc {
                continue;
            }
            let Some(pdo) = new_device() else {
                continue;
            };
            let mut found = Node::new(pdo as usize, root_pdo, 1);
            found.instance = instance;
            found.device_id = format!("ROOT\\{device_key}");
            // SAFETY: fresh PDO owned by PnpManager.
            if unsafe { adopt(pdo, found) }.is_none() {
                // SAFETY: never adopted.
                unsafe { device::IoDeleteDevice(pdo) };
            }
        }
    }
}

/// Read a `REG_MULTI_SZ` value from the device's `Enum` key as UTF-16 units
/// ending with a double NUL.
fn enum_multi_sz(instance: &str, value_name: &str) -> Option<Vec<u16>> {
    let (_, data) = crate::cm::read(&registry::enum_key(instance), value_name).ok()?;
    let mut units: Vec<u16> = data
        .as_chunks::<2>()
        .0
        .iter()
        .map(|b| u16::from_le_bytes(*b))
        .collect();
    if units.is_empty() {
        return None;
    }
    while units.last() == Some(&0) {
        units.pop();
    }
    if units.is_empty() {
        return None;
    }
    units.push(0);
    units.push(0);
    Some(units)
}

/// The manager's dispatch routine for Plug and Play requests.
///
/// # Safety
/// Called as a dispatch routine.
unsafe extern "C" fn dispatch_pnp(device: *mut DEVICE_OBJECT, request: *mut IRP) -> NTSTATUS {
    // SAFETY: a live request at this driver's location, for one of its
    // devices.
    unsafe {
        let location = (*request).CurrentStackLocation;
        let parameters = (*location).Parameters;
        let is_root = device == root();
        let found = node::get(device as usize);
        match (*location).MinorFunction {
            IRP_MN_QUERY_DEVICE_RELATIONS => match parameters[0] as u32 {
                BUS_RELATIONS if is_root => {
                    discover_registry_devices();
                    let children = node::get(device as usize)
                        .map(|node| node.children)
                        .unwrap_or_default();
                    match relations_of(&children) {
                        0 => complete(request, STATUS_INSUFFICIENT_RESOURCES, 0),
                        list => complete(request, STATUS_SUCCESS, list),
                    }
                }
                TARGET_DEVICE_RELATION if !is_root => match relations_of(&[device as usize]) {
                    0 => complete(request, STATUS_INSUFFICIENT_RESOURCES, 0),
                    list => complete(request, STATUS_SUCCESS, list),
                },
                _ => complete_unchanged(request),
            },
            IRP_MN_QUERY_ID => {
                let Some(found) = found.filter(|_| !is_root) else {
                    return complete_unchanged(request);
                };
                let (device_id, instance_id) = found
                    .instance
                    .rsplit_once('\\')
                    .unwrap_or((&found.instance, ""));
                let answer: Vec<u16> = match parameters[0] as u32 {
                    BUS_QUERY_DEVICE_ID => device_id.encode_utf16().chain([0]).collect(),
                    BUS_QUERY_INSTANCE_ID => instance_id.encode_utf16().chain([0]).collect(),
                    BUS_QUERY_HARDWARE_IDS => enum_multi_sz(&found.instance, "HardwareID")
                        .unwrap_or_else(|| device_id.encode_utf16().chain([0, 0]).collect()),
                    BUS_QUERY_COMPATIBLE_IDS => {
                        let Some(ids) = enum_multi_sz(&found.instance, "CompatibleIDs") else {
                            return complete_unchanged(request);
                        };
                        ids
                    }
                    _ => return complete_unchanged(request),
                };
                match pool_string(&answer) {
                    0 => complete(request, STATUS_INSUFFICIENT_RESOURCES, 0),
                    text => complete(request, STATUS_SUCCESS, text),
                }
            }
            IRP_MN_QUERY_CAPABILITIES => {
                if !is_root && found.as_ref().is_some_and(|node| !node.reported) {
                    let caps = parameters[0] as *mut DEVICE_CAPABILITIES;
                    if !caps.is_null() {
                        let flags = &raw mut (*caps).Flags;
                        flags.write(flags.read() | DEVICE_CAPABILITY_UNIQUE_ID);
                    }
                }
                let information = (*request).IoStatus.Information;
                complete(request, STATUS_SUCCESS, information)
            }
            // What a device that is simply there succeeds.
            IRP_MN_START_DEVICE
            | IRP_MN_QUERY_STOP_DEVICE
            | IRP_MN_CANCEL_STOP_DEVICE
            | IRP_MN_STOP_DEVICE
            | IRP_MN_QUERY_REMOVE_DEVICE
            | IRP_MN_CANCEL_REMOVE_DEVICE
            | IRP_MN_REMOVE_DEVICE
            | IRP_MN_SURPRISE_REMOVAL => {
                let information = (*request).IoStatus.Information;
                complete(request, STATUS_SUCCESS, information)
            }
            _ => complete_unchanged(request),
        }
    }
}

/// The manager's dispatch routine for power requests: its devices have
/// no power state of their own.
///
/// # Safety
/// Called as a dispatch routine.
unsafe extern "C" fn dispatch_power(_: *mut DEVICE_OBJECT, request: *mut IRP) -> NTSTATUS {
    irp::PoStartNextPowerIrp(request);
    // SAFETY: a live request at this driver's location.
    unsafe { complete_unchanged(request) }
}

/// Make the manager's driver and the root device, with its node and
/// its key.
pub fn init() -> Result<(), &'static str> {
    let made = driver::builtin("PnpManager", |object| {
        // SAFETY: the driver object being set up, which nothing else
        // knows yet.
        unsafe {
            (*object).MajorFunction[usize::from(IRP_MJ_PNP)] = Some(dispatch_pnp);
            (*object).MajorFunction[usize::from(IRP_MJ_POWER)] = Some(dispatch_power);
        }
    })
    .map_err(|_| "the Plug and Play manager's driver object could not be made")?;
    DRIVER.store(made, Ordering::Release);
    let root = new_device().ok_or("no memory for the root device")?;
    ROOT.store(root, Ordering::Release);
    let mut top = Node::new(root as usize, 0, 0);
    top.instance = ROOT_INSTANCE.into();
    top.state = State::Started;
    // Windows' root: unique, silently installed, usable raw.
    top.capabilities = DEVICE_CAPABILITY_UNIQUE_ID
        | DEVICE_CAPABILITY_SILENT_INSTALL
        | DEVICE_CAPABILITY_RAW_DEVICE_OK;
    top.ui_number = 0;
    registry::write_identity(&top)
        .and_then(|()| {
            crate::cm::write_path(
                &registry::enum_key(ROOT_INSTANCE),
                &[("ConfigFlags", REG_DWORD, &[0; 4])],
            )
        })
        .map_err(|_| "the root device's key could not be written")?;
    // SAFETY: a device of the manager's, just made.
    unsafe { adopt(root, top) }.ok_or("no memory for the root device's node")
}

/// A device of the manager's: unnamed for the root, else named by the
/// I/O manager.
fn new_device() -> Option<*mut DEVICE_OBJECT> {
    let mut made = core::ptr::null_mut();
    let characteristics = if root().is_null() {
        0
    } else {
        FILE_AUTOGENERATED_DEVICE_NAME
    };
    // SAFETY: the manager's driver object; no name; `made` is writable.
    let status = unsafe {
        device::IoCreateDevice(
            DRIVER.load(Ordering::Acquire),
            0,
            core::ptr::null(),
            FILE_DEVICE_CONTROLLER,
            characteristics,
            0,
            &raw mut made,
        )
    };
    if !nt_success(status) {
        return None;
    }
    // SAFETY: the device just made, which nothing else knows yet.
    unsafe {
        let flags = &raw mut (*made).Flags;
        flags.write((flags.read() | DO_BUS_ENUMERATED_DEVICE) & !DO_DEVICE_INITIALIZING);
    }
    Some(made)
}

/// Enter `node` in the tree for `device`, which the tree then holds a
/// reference to, and point the device at it.
///
/// # Safety
/// `device` is a live device of the manager's.
unsafe fn adopt(device: *mut DEVICE_OBJECT, node: Node) -> Option<()> {
    let address = node::insert(node)?;
    // SAFETY: a live device of the manager's.
    unsafe {
        crate::ob::object::reference(device.cast());
        (&raw mut (*(*device).DeviceObjectExtension).DeviceNode).write(address as PVOID);
    }
    Some(())
}

/// Report a device its own driver detected, as Windows'
/// [`IoReportDetectedDevice`](https://learn.microsoft.com/en-us/windows-hardware/drivers/ddi/ntddk/nf-ntddk-ioreportdetecteddevice)
/// does for a driver that passes no resources: the device becomes
/// `ROOT\<service>\0000`, a child of the root, with a physical device
/// object of the manager's, which is returned. The reporting driver
/// attaches its own device to it and serves it: the manager calls no
/// `AddDevice` for it and does not start it, and asks its stack for
/// its hardware identifiers and its children when it next settles.
///
/// Its key gets what Windows' report writes: `DeviceReported`,
/// `Service` naming the driver object, and the compatible identifiers
/// `DETECTED<interface>\<service>` (for a bus type given) and
/// `DETECTED\<service>`.
pub fn report_detected_device(
    service: &str,
    interface: Option<&str>,
) -> Result<*mut DEVICE_OBJECT, NTSTATUS> {
    let instance = format!("ROOT\\{service}\\0000");
    if node::by_instance(&instance).is_some() {
        return Err(STATUS_OBJECT_NAME_COLLISION);
    }
    let pdo = new_device().ok_or(STATUS_INSUFFICIENT_RESOURCES)?;
    let mut found = Node::new(pdo as usize, root() as usize, 1);
    found.instance = instance;
    found.reported = true;
    found.device_id = format!("ROOT\\{service}");
    found.compatible_ids = interface
        .map(|interface| format!("DETECTED{interface}\\{service}"))
        .into_iter()
        .chain([format!("DETECTED\\{service}")])
        .collect();
    let key = registry::enum_key(&found.instance);
    let compatible: Vec<u8> = ids::to_multi_sz(&found.compatible_ids)
        .into_iter()
        .flat_map(u16::to_le_bytes)
        .collect();
    let written = crate::cm::write_path(
        &key,
        &[
            ("DeviceReported", REG_DWORD, &1u32.to_le_bytes()),
            ("Service", REG_SZ, &ids::sz(&format!("\\Driver\\{service}"))),
            ("CompatibleIDs", REG_MULTI_SZ, &compatible),
        ],
    )
    .and_then(|()| {
        crate::cm::write_path(
            &format!("{key}\\Control"),
            &[("DeviceReported", REG_DWORD, &1u32.to_le_bytes())],
        )
    });
    // SAFETY: a device of the manager's, just made.
    if written.is_err() || unsafe { adopt(pdo, found) }.is_none() {
        // SAFETY: the device just made, which nothing else knows.
        unsafe { device::IoDeleteDevice(pdo) };
        return Err(STATUS_INSUFFICIENT_RESOURCES);
    }
    Ok(pdo)
}

/// Take a reported device, and everything below it, out of the tree
/// again and delete its physical device object. The reporting driver
/// has detached and deleted its own device. NK's own: what a test's
/// driver does when it is done.
pub fn remove_reported_device(pdo: *mut DEVICE_OBJECT) {
    super::engine::remove_now(pdo as usize, false);
    // SAFETY: a device `report_detected_device` made, out of the tree
    // now and with nothing attached.
    unsafe { device::IoDeleteDevice(pdo) };
}

/// The names Windows gives the bus types (`INTERFACE_TYPE`) in a
/// reported device's compatible identifier, by number.
const BUS_TYPES: [&str; 18] = [
    "Internal",
    "Isa",
    "Eisa",
    "MicroChannel",
    "TurboChannel",
    "PCIBus",
    "VMEBus",
    "NuBus",
    "PCMCIABus",
    "CBus",
    "MPIBus",
    "MPSABus",
    "ProcessorInternal",
    "InternalPowerBus",
    "PNPISABus",
    "PNPBus",
    "Vmcs",
    "ACPIBus",
];

/// [`IoReportDetectedDevice`](https://learn.microsoft.com/en-us/windows-hardware/drivers/ddi/ntddk/nf-ntddk-ioreportdetecteddevice):
/// report a device `driver` detected itself: [`report_detected_device`]
/// under the driver's service name, the bus type naming the first
/// compatible identifier (none for `InterfaceTypeUndefined`, -1, as
/// `volmgr.sys` passes). The physical device object is returned in
/// `device`.
///
/// Partial: a report that names resources, or hands back a device the
/// driver reported at an earlier boot, stops the system by name: NK
/// keeps no reported devices from boot to boot, and no binary NK runs
/// reports resources.
///
/// # Safety
/// `driver` is a live driver object; `device` is readable and writable.
#[allow(non_snake_case)]
pub unsafe extern "C" fn IoReportDetectedDevice(
    driver: *mut nk_ntabi::io::DRIVER_OBJECT,
    bus_type: i32,
    _bus_number: u32,
    _slot_number: u32,
    resources: *mut core::ffi::c_void,
    requirements: *mut core::ffi::c_void,
    _resources_assigned: u8,
    device: *mut *mut DEVICE_OBJECT,
) -> NTSTATUS {
    // SAFETY: per the contract; the driver's name is a counted string
    // that stays while the driver object does.
    let (service, given) = unsafe {
        let name = crate::rtl::copy_unicode(&raw const (*driver).DriverName);
        let name = alloc::string::String::from_utf16_lossy(&name);
        let service = name.rsplit('\\').next().unwrap_or("").into();
        (service, device.read())
    };
    let service: alloc::string::String = service;
    if !given.is_null() || !resources.is_null() || !requirements.is_null() {
        crate::kd::bugcheck(format_args!(
            "IoReportDetectedDevice: {service} reported a device with resources or one of an \
             earlier boot, which NK does not implement"
        ));
    }
    let interface = usize::try_from(bus_type)
        .ok()
        .and_then(|number| BUS_TYPES.get(number).copied());
    match report_detected_device(&service, interface) {
        Ok(pdo) => {
            // SAFETY: per the contract.
            unsafe { device.write(pdo) };
            STATUS_SUCCESS
        }
        Err(status) => status,
    }
}
